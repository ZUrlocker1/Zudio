// Copyright (c) 2026 Zack Urlocker
//
// Chill Soho songs have no vocal, so Lead 1 stands in for the singer: a lead shaped like a sung
// melody is what makes them sound like songs rather than backing tracks. Three Soho rules,
// measured per song from the corpus — see "Lead 1 — the sax voice" in docs/chill-soho-plan.md —
// and two base Chill rules reused as they are:
//
//   CHL-LD1-010 Soho Counter-Line — 30%: 8–13 note phrases, a longer note to end, open-ended
//   CHL-LD1-012 Tight Hook        — 20%: a 3–6 note figure within a tenth, restated and varied
//   CHL-LD1-004 Blues lead        — 20%: base Chill's rule
//   CHL-LD1-001 Long phrase       — 15%: base Chill's rule
//   CHL-LD1-011 Sustained Tone    — 15%: one long note per phrase, held two to three bars, long rests
//
// St Germain staccato (CHL-LD1-005) never plays here, and neither do the other base Chill rules.
//
// The records repeat more than Zudio should — they have a vocal, lyrics and a radio form to carry
// the listener. So the parts are measured from the records but vary on Zudio's own schedule:
// rest windows (one per ~22 bars, 4–8 bars each), no unbroken stretch over 14–16 bars, and the
// remembered phrase mutates every 8–12 bars.

import Foundation

extension ChillLeadGenerator {

    static let sohoLead1Rules = ["CHL-LD1-010", "CHL-LD1-011", "CHL-LD1-012", "CHL-LD1-004", "CHL-LD1-001"]

    /// The two base Chill rules Soho reuses. They are generated by base Chill's own lead code,
    /// then given Soho's rest windows, stretch cap and Remix Break pickup.
    static let sohoReusedLead1Rules: Set<String> = ["CHL-LD1-004", "CHL-LD1-001"]

    /// Vocal-derived cells in semitones, weighted by how often each occurs in the named Vocal
    /// tracks. Repeated pitches are the defining feature of these melodies, not noise: a line
    /// that always moves will not sound like this music.
    private static let vocalCells: [(cell: [Int], weight: Double)] = [
        ([0, 0, -2], 30), ([2, -2, 2], 25), ([0, 0, 2], 24), ([-2, 2, -2], 22), ([0, 0, 0], 20),
        ([0, 2, -2], 19), ([0, -2, 2], 17), ([0, 0, 2, -2], 13), ([-2, -1, 0], 12), ([2, -2, -3], 12),
    ]

    /// Sax-derived cells, weighted at a third of their counts: the vocal lines are the better
    /// model, and the sax aggregate is skewed toward Black Cow's busy horn writing.
    private static let saxCells: [(cell: [Int], weight: Double)] = [
        ([3, 2, 2], 29), ([2, 3, 2], 24), ([2, 2, 1], 22), ([-3, -2, 2], 18), ([1, -3, -2], 17),
    ]

    /// The default bank: vocal-led, with the sax cells at a third of their counts. Tight Hook
    /// uses it, and its repeated pitches are what make that rule sound sung.
    private static let cellBank = vocalCells + saxCells.map { (cell: $0.cell, weight: $0.weight / 3) }

    /// Counter-Line's bank gives the sax cells their full weight. Measured, this rule comes from
    /// the reed and flute lines as much as the vocals — Smooth Operator, Black Cow — and those
    /// move stepwise where the vocals repeat. On the shared bank it drew 63% repeated pitches and
    /// barely travelled, which is why it sounded like a weaker Tight Hook (Zack, 2026-10-11).
    private static let counterLineCells = vocalCells + saxCells

    /// Durations of a phrase's first four notes, in steps. Three eighths then a quarter dominates.
    private static let openingRhythms: [(durs: [Int], weight: Double)] = [
        ([2, 2, 2, 4], 26), ([2, 2, 4, 2], 10), ([2, 2, 2, 2], 7), ([2, 2, 4, 4], 6), ([4, 2, 2, 2], 5),
    ]

    /// A melodic figure: `durs[i]` is how long note i lasts, and `intervals[i]` the semitone step
    /// from note i to note i + 1.
    struct SohoPhrase {
        var intervals: [Int]
        var durs: [Int]
    }

    // MARK: - Lead 1

    static func sohoLead1(
        frame: GlobalMusicalFrame,
        structure: SongStructure,
        leadInstrument: ChillLeadInstrument,
        breakdownStyle: ChillBreakdownStyle,
        forceRuleID: String?,
        rng: inout SeededRNG,
        usedRuleIDs: inout Set<String>
    ) -> (events: [MIDIEvent], phraseOnsets: [(startBar: Int, endBar: Int)], handoffBars: Set<Int>) {
        let ruleID: String
        if let forced = forceRuleID, sohoLead1Rules.contains(forced) {
            ruleID = forced
        } else {
            // Counter-Line was 50% and carried too many songs.
            let r = rng.nextDouble()
            ruleID = r < 0.30 ? "CHL-LD1-010"
                   : r < 0.50 ? "CHL-LD1-012"
                   : r < 0.70 ? "CHL-LD1-004"
                   : r < 0.85 ? "CHL-LD1-001"
                   :            "CHL-LD1-011"
        }
        if sohoReusedLead1Rules.contains(ruleID) {
            return reusedLead1(ruleID, frame: frame, structure: structure, leadInstrument: leadInstrument,
                               breakdownStyle: breakdownStyle, rng: &rng, usedRuleIDs: &usedRuleIDs)
        }
        usedRuleIDs.insert(ruleID)

        let (regLow, regHigh) = register(for: leadInstrument)
        let pool = Array(Set(scaleNotes(frame: frame).filter { $0 >= regLow && $0 <= regHigh })).sorted()
        guard pool.count >= 4 else { return ([], [], []) }

        // Where Lead 1 may play: the groove and the outro. Never the intro or a breakdown, never
        // the cold-start bar, and never the last two bars of a cold stop or of the song.
        let lastPlayable: Int = {
            if case .coldStop = structure.outroStyle, let end = structure.outroSection?.endBar { return end - 3 }
            return frame.totalBars - 2
        }()
        func playable(_ bar: Int) -> Bool {
            guard bar >= 1, bar <= lastPlayable else { return false }
            switch structure.section(atBar: bar)?.label {
            case .A?, .B?, .outro?: return true
            default:                return false
            }
        }
        guard let firstPlayable = (0..<frame.totalBars).first(where: playable) else { return ([], [], []) }

        // Remix Break returns: Lead 1 picks up into the downbeat on both exits, so the first bar
        // back is never a rest and its own phrase starts after the landing note.
        let remixReturns: [Int] = breakdownStyle == .sohoRemix
            ? structure.sections.filter { $0.label == .bridge }.map(\.endBar).filter(playable)
            : []

        var rest = Set<Int>()
        if ruleID != "CHL-LD1-011" {   // Sustained Tone already rests five bars at a time
            rest = LeadGenerator.buildRestBars(entryBar: firstPlayable, totalBars: frame.totalBars, rng: &rng)
            for bar in remixReturns { rest.remove(bar); rest.remove(bar - 1) }
        }
        func open(_ bar: Int) -> Bool { playable(bar) && !rest.contains(bar) }

        var events: [MIDIEvent] = []
        var onsets: [(startBar: Int, endBar: Int)] = []

        switch ruleID {
        case "CHL-LD1-011":
            sustainedTone(frame: frame, structure: structure, pool: pool, firstPlayable: firstPlayable,
                          open: open, remixReturns: remixReturns,
                          events: &events, onsets: &onsets, rng: &rng)
        case "CHL-LD1-012":
            tightHook(frame: frame, structure: structure, pool: pool, firstPlayable: firstPlayable,
                      open: open, remixReturns: remixReturns,
                      events: &events, onsets: &onsets, rng: &rng)
        default:
            counterLine(frame: frame, structure: structure, pool: pool, firstPlayable: firstPlayable,
                        open: open, remixReturns: remixReturns,
                        events: &events, onsets: &onsets, rng: &rng)
        }

        events += remixPickups(remixReturns, structure: structure, frame: frame, pool: pool, rng: &rng)

        // No unbroken stretch over 14–16 bars: this substyle is built on space. Motorik uses 20.
        if ruleID != "CHL-LD1-011" {
            events = LeadGenerator.capUnbrokenStretch(events, maxBars: 14 + rng.nextInt(upperBound: 3),
                                                      totalBars: frame.totalBars, rng: &rng)
        }
        let soundingBars = Set(events.map { $0.stepIndex / 16 })
        onsets = onsets.filter { o in (o.startBar..<o.endBar).contains(where: soundingBars.contains) }
        return (events.sorted { ($0.stepIndex, $0.note) < ($1.stepIndex, $1.note) }, onsets, [])
    }

    // MARK: - Reused base Chill rules

    /// CHL-LD1-004 Blues lead and CHL-LD1-001 Long phrase, played by base Chill's lead code
    /// exactly as in a regular Chill song, then thinned to Soho's space: rest windows of 4–8
    /// bars every ~22, no unbroken stretch over 14–16 bars, and the pickup into a Remix Break
    /// return. Intro and breakdown behaviour stay base Chill's.
    private static func reusedLead1(
        _ ruleID: String, frame: GlobalMusicalFrame, structure: SongStructure,
        leadInstrument: ChillLeadInstrument, breakdownStyle: ChillBreakdownStyle,
        rng: inout SeededRNG, usedRuleIDs: inout Set<String>
    ) -> (events: [MIDIEvent], phraseOnsets: [(startBar: Int, endBar: Int)], handoffBars: Set<Int>) {
        let (base, _, handoff) = generateLead1(
            frame: frame, structure: structure, leadInstrument: leadInstrument,
            beatStyle: .electronic,   // only consulted by the St Germain staccato roll, which forcing skips
            breakdownStyle: breakdownStyle, forceRuleID: ruleID,
            rng: &rng, usedRuleIDs: &usedRuleIDs)

        let remixReturns: [Int] = breakdownStyle == .sohoRemix
            ? structure.sections.filter { $0.label == .bridge }.map(\.endBar).filter { $0 < frame.totalBars - 2 }
            : []
        let firstGroove = structure.sections.first { $0.label == .A }?.startBar ?? 0
        var rest = LeadGenerator.buildRestBars(entryBar: firstGroove, totalBars: frame.totalBars, rng: &rng)
        for bar in remixReturns { rest.remove(bar) }
        // Leave the remix return's first six steps to the landing note.
        let landing = Set(remixReturns.flatMap { ($0 * 16)..<($0 * 16 + 6) })
        var events = base.filter { !rest.contains($0.stepIndex / 16) && !landing.contains($0.stepIndex) }

        let (regLow, regHigh) = register(for: leadInstrument)
        let pool = Array(Set(scaleNotes(frame: frame).filter { $0 >= regLow && $0 <= regHigh })).sorted()
        if pool.count >= 4 {
            events += remixPickups(remixReturns, structure: structure, frame: frame, pool: pool, rng: &rng)
        }
        events = LeadGenerator.capUnbrokenStretch(events, maxBars: 14 + rng.nextInt(upperBound: 3),
                                                  totalBars: frame.totalBars, rng: &rng)
        events.sort { ($0.stepIndex, $0.note) < ($1.stepIndex, $1.note) }

        // Phrase spans for Lead 2 to answer around, rebuilt from what survived: a gap of a bar or
        // more ends a phrase.
        var onsets: [(startBar: Int, endBar: Int)] = []
        for bar in Set(events.map { $0.stepIndex / 16 }).sorted() {
            if let last = onsets.last, bar <= last.endBar {
                onsets[onsets.count - 1].endBar = bar + 1
            } else {
                onsets.append((startBar: bar, endBar: bar + 1))
            }
        }
        return (events, onsets, handoff)
    }

    // MARK: - CHL-LD1-010 Soho Counter-Line

    /// Sung-melody phrases answering an implied vocal: 6–11 notes in eighths with a longer note
    /// to end, rests of about a bar and a half between them, and phrases that land somewhere new
    /// rather than closing (0 of 22 close in Smooth Operator).
    ///
    /// The first phrase is remembered and comes back in about 40% of later phrases, mutating
    /// slightly every 8–12 bars so it is recognisable but never identical.
    private static func counterLine(frame: GlobalMusicalFrame, structure: SongStructure, pool: [Int],
                                    firstPlayable: Int, open: (Int) -> Bool, remixReturns: [Int],
                                    events: inout [MIDIEvent], onsets: inout [(startBar: Int, endBar: Int)],
                                    rng: inout SeededRNG) {
        var motif: SohoPhrase? = nil
        var contour = rng.nextInt(upperBound: 3)
        var nextMutation = 0
        var lastPitch = pool[pool.count / 3]
        var bar = firstPlayable + rng.nextInt(upperBound: 2)

        while bar < frame.totalBars {
            guard open(bar) else { bar += 1; continue }
            if structure.section(atBar: bar)?.label == .outro && rng.nextDouble() < 0.5 { bar += 2; continue }

            var span = 0
            while span < 4 && open(bar + span) { span += 1 }
            let offset = remixReturns.contains(bar) ? 8 : [0, 2, 4, 8][rng.weightedPick([35, 30, 15, 20])]

            let phrase: SohoPhrase
            if var m = motif, rng.nextDouble() < 0.35 {
                if bar >= nextMutation {
                    m = mutateOpen(m, rng: &rng)
                    motif = m
                    nextMutation = bar + 8 + rng.nextInt(upperBound: 5)
                }
                phrase = m
            } else {
                // A fresh phrase travels: up, down, or up then back. Successive phrases take
                // different shapes, which is what stops the rule circling one figure.
                contour = (contour + 1 + rng.nextInt(upperBound: 2)) % 3
                phrase = counterLinePhrase(contour: contour, rng: &rng)
                if motif == nil { motif = phrase; nextMutation = bar + 8 + rng.nextInt(upperBound: 5) }
            }

            let start = anchor(near: lastPitch, bar: bar, structure: structure, frame: frame, pool: pool)
            let notes = realise(phrase, at: bar * 16 + offset, from: start, limit: (bar + span) * 16,
                                pool: pool, vel: velocity(at: bar, structure: structure), rng: &rng)
            guard let last = notes.last else { bar += 1; continue }
            events += notes
            lastPitch = Int(last.note)
            let endBar = (last.stepIndex + last.durationSteps + 15) / 16
            onsets.append((startBar: bar, endBar: Swift.max(bar + 1, endBar)))
            // Rests of about a bar and a half: the partial bar after the phrase plus 0–2 more.
            bar = endBar + [0, 1, 2][rng.weightedPick([35, 45, 20])]
        }
    }

    /// A Counter-Line phrase: 8–13 notes, the measured opening rhythm, then a tail that is not
    /// simply more eighths. `contour` is 0 rising, 1 falling, 2 an arch — the cells keep their
    /// shape but are turned to follow it, so the line travels instead of circling one register.
    ///
    /// Lengthened and widened after Zack heard it beside Tight Hook (2026-10-11): both drew on
    /// the same cells and the same opening rhythms, so the longer rule did not sound longer. The
    /// corpus separates them — Counter-Line's compass measures 19–29 semitones against the hook's
    /// 10 — and leaps of a fourth or more are 17–20% of its intervals, which the cell bank alone,
    /// none of whose steps exceed 3 semitones, could never produce.
    private static func counterLinePhrase(contour: Int, rng: inout SeededRNG) -> SohoPhrase {
        let n = 8 + rng.nextInt(upperBound: 6)                       // 8–13 notes
        var intervals: [Int] = []
        while intervals.count < n - 1 {
            var cell = pickCell(from: counterLineCells, rng: &rng)
            // Turn the cell to follow the contour: rising in the first half of an arch, falling
            // in the second. A cell of repeated pitches is unaffected, which keeps the repeats.
            let rising = contour == 0 || (contour == 2 && intervals.count * 2 < n)
            let sum = cell.reduce(0, +)
            if sum != 0 && (sum > 0) != rising && rng.nextDouble() < 0.70 { cell = cell.map { -$0 } }
            intervals += cell
            // A leap between cells, where a singer takes a breath and comes back in somewhere
            // new. 4ths, 5ths and the occasional octave, placed to follow the contour. At one
            // leap per cell boundary this lands near the measured 17–20% of all intervals;
            // the cells themselves never step more than 3 semitones.
            if intervals.count < n - 2 && rng.nextDouble() < 0.75 {
                let size = [5, 7, 12][rng.weightedPick([0.45, 0.40, 0.15])]
                intervals.append(rising ? size : -size)
            }
        }
        intervals = keepOpen(Array(intervals.prefix(n - 1)))

        var durs = openingRhythms[rng.weightedPick(openingRhythms.map(\.weight))].durs
        // The tail is mixed, not a run of eighths: a pair of sixteenths, a dotted eighth, a held
        // note, or an eighth. Sixteenths come in pairs so the line keeps its eighth-note pulse.
        while durs.count < n {
            switch rng.weightedPick([0.50, 0.18, 0.17, 0.15]) {
            case 1:  durs += [1, 1]
            case 2:  durs.append(3)
            case 3:  durs.append(4)
            default: durs.append(2)
            }
        }
        durs = Array(durs.prefix(n))
        durs[n - 1] = 4 + 2 * rng.nextInt(upperBound: 3)             // 4, 6 or 8 — the longer last note
        // A breath inside the phrase, roughly two-thirds through: the note before it is held, so
        // the line is one phrase with a lift in it rather than two phrases.
        if n >= 9 && rng.nextDouble() < 0.35 {
            durs[(n * 2) / 3] += 2 + rng.nextInt(upperBound: 3)
        }
        return SohoPhrase(intervals: intervals, durs: durs)
    }

    /// One small change: an interval nudged by a step, or a quarter and an eighth swapped. The
    /// last note keeps its length so the phrase still ends on the longer note, and the result is
    /// kept open-ended.
    private static func mutateOpen(_ p: SohoPhrase, rng: inout SeededRNG) -> SohoPhrase {
        var m = p
        if rng.nextDouble() < 0.65, !m.intervals.isEmpty {
            let i = rng.nextInt(upperBound: m.intervals.count)
            m.intervals[i] += (rng.nextDouble() < 0.5 ? 1 : -1) * (rng.nextDouble() < 0.6 ? 2 : 1)
            m.intervals = keepOpen(m.intervals)
        } else if m.durs.count >= 3 {
            let i = rng.nextInt(upperBound: m.durs.count - 2)
            m.durs.swapAt(i, i + 1)
        }
        return m
    }

    /// Counter-Line and Sustained Tone phrases never return to their first pitch.
    private static func keepOpen(_ intervals: [Int]) -> [Int] {
        guard var last = intervals.last, intervals.reduce(0, +) == 0 else { return intervals }
        last += last >= 0 ? 2 : -2
        return Array(intervals.dropLast()) + [last]
    }

    // MARK: - CHL-LD1-012 Tight Hook

    /// A 3–6 note figure inside a tenth, stated two to four times in succession with short rests,
    /// then a bar or two off. Measured from Avalon: it recurs and varies rather than developing.
    /// About 30% of hooks close on their first pitch; closure belongs to this rule alone, so a
    /// closed hook mutates with the interval-preserving trade Motorik Europe's `varyCell` uses.
    private static func tightHook(frame: GlobalMusicalFrame, structure: SongStructure, pool: [Int],
                                  firstPlayable: Int, open: (Int) -> Bool, remixReturns: [Int],
                                  events: inout [MIDIEvent], onsets: inout [(startBar: Int, endBar: Int)],
                                  rng: inout SeededRNG) {
        let closed = rng.nextDouble() < 0.30
        var hook = hookPhrase(closed: closed, rng: &rng)
        var nextMutation = firstPlayable + 8 + rng.nextInt(upperBound: 5)
        let home = pool[pool.count / 3]
        let length = hook.durs.reduce(0, +)
        let preferred = length <= 12 ? [0, 2, 4][rng.nextInt(upperBound: 3)] : 0
        var bar = firstPlayable + rng.nextInt(upperBound: 2)

        while bar < frame.totalBars {
            guard open(bar) else { bar += 1; continue }
            if structure.section(atBar: bar)?.label == .outro && rng.nextDouble() < 0.5 { bar += 2; continue }

            if bar >= nextMutation {
                hook = closed ? tradeIntervals(hook, rng: &rng) : nudgeWithinCompass(hook, rng: &rng)
                nextMutation = bar + 8 + rng.nextInt(upperBound: 5)
            }

            let statements = 2 + rng.nextInt(upperBound: 3)          // 2–4 in a row
            let everyOther = rng.nextDouble() < 0.30
            let episodeStart = bar
            var stated = 0
            while stated < statements, bar < frame.totalBars, open(bar) {
                var figure = hook
                // One statement in five is an answer: the last step goes somewhere else.
                if stated > 0, rng.nextDouble() < 0.20, let lastIv = figure.intervals.last {
                    figure.intervals[figure.intervals.count - 1] = lastIv + (lastIv >= 0 ? -2 : 2)
                }
                let offset = remixReturns.contains(bar) ? 8 : preferred
                let start = anchor(near: home, bar: bar, structure: structure, frame: frame, pool: pool)
                events += realise(figure, at: bar * 16 + offset, from: start, limit: (bar + 1) * 16,
                                  pool: pool, vel: velocity(at: bar, structure: structure), rng: &rng)
                stated += 1
                bar += everyOther ? 2 : 1
            }
            if stated > 0 { onsets.append((startBar: episodeStart, endBar: bar)) }
            bar += 1 + rng.nextInt(upperBound: 2)                    // a bar or two off
        }
    }

    private static func hookPhrase(closed: Bool, rng: inout SeededRNG) -> SohoPhrase {
        let n = 3 + rng.nextInt(upperBound: 4)                       // 3–6 notes
        var intervals: [Int] = [0, 2, -2]
        for _ in 0..<12 {
            var c: [Int] = []
            while c.count < n - 1 { c += pickCell(rng: &rng) }
            c = Array(c.prefix(n - 1))
            if closed && c.count >= 2 { c[c.count - 1] = -c.dropLast().reduce(0, +) }
            if compass(c) <= 10 && c.allSatisfy({ abs($0) <= 7 }) { intervals = c; break }
        }
        intervals = Array(intervals.prefix(n - 1))
        var durs = Array(openingRhythms[rng.weightedPick(openingRhythms.map(\.weight))].durs.prefix(n))
        while durs.count < n { durs.append(2) }
        durs[n - 1] = 4
        return SohoPhrase(intervals: intervals, durs: durs)
    }

    /// Range of a figure in semitones, from its running pitch.
    private static func compass(_ intervals: [Int]) -> Int {
        var p = 0, lo = 0, hi = 0
        for iv in intervals { p += iv; lo = Swift.min(lo, p); hi = Swift.max(hi, p) }
        return hi - lo
    }

    /// Nudge one interval and take the same amount from another, so a closed hook still closes.
    private static func tradeIntervals(_ p: SohoPhrase, rng: inout SeededRNG) -> SohoPhrase {
        guard p.intervals.count >= 3 else { return p }
        var m = p
        let a = rng.nextInt(upperBound: m.intervals.count - 1)
        let b = a + 1 + rng.nextInt(upperBound: m.intervals.count - 1 - a)
        let nudge = (rng.nextDouble() < 0.5 ? 1 : -1) * (rng.nextDouble() < 0.7 ? 1 : 2)
        m.intervals[a] += nudge
        m.intervals[b] -= nudge
        return compass(m.intervals) <= 10 ? m : p
    }

    private static func nudgeWithinCompass(_ p: SohoPhrase, rng: inout SeededRNG) -> SohoPhrase {
        guard !p.intervals.isEmpty else { return p }
        var m = p
        let i = rng.nextInt(upperBound: m.intervals.count)
        m.intervals[i] += rng.nextDouble() < 0.5 ? 2 : -2
        return compass(m.intervals) <= 10 ? m : p
    }

    // MARK: - CHL-LD1-011 Sustained Tone

    /// A sax holding long tones, closer to a pad than a melody: one note per phrase, held two
    /// to three bars, then four to seven bars of rest. Measured from More Than This — thirteen
    /// notes in the whole song, median 47.6 steps, inside a 12-semitone compass.
    private static func sustainedTone(frame: GlobalMusicalFrame, structure: SongStructure, pool: [Int],
                                      firstPlayable: Int, open: (Int) -> Bool, remixReturns: [Int],
                                      events: inout [MIDIEvent], onsets: inout [(startBar: Int, endBar: Int)],
                                      rng: inout SeededRNG) {
        let centre = pool[pool.count / 2]
        let band = pool.filter { abs($0 - centre) <= 6 }
        var previous = -1
        var bar = firstPlayable + rng.nextInt(upperBound: 4)

        while bar < frame.totalBars {
            guard open(bar), !remixReturns.contains(bar) else { bar += 1; continue }
            var span = 0
            while span < 4 && open(bar + span) { span += 1 }
            guard span >= 2 else { bar += span + 1; continue }

            let offset = rng.nextDouble() < 0.70 ? 0 : 2
            let hold = Swift.min(32 + rng.nextInt(upperBound: 17), span * 16 - offset - 2)   // 32–48 steps
            guard let chord = structure.chordPlan.first(where: { $0.contains(bar: bar) }) else { bar += 1; continue }
            // A colour tone where there is one (the 9th, the 6th), else a chord tone; never the
            // pitch just held, so successive tones move.
            let colour = band.filter { chord.scaleTensions.contains($0 % 12) && $0 != previous }
            let tones  = band.filter { chord.chordTones.contains($0 % 12) && $0 != previous }
            let choices = (!colour.isEmpty && rng.nextDouble() < 0.4) ? colour : (tones.isEmpty ? band : tones)
            guard !choices.isEmpty else { bar += 1; continue }
            let note = choices[rng.nextInt(upperBound: choices.count)]
            previous = note
            let vel = Swift.max(40, velocity(at: bar, structure: structure) - 6 + rng.nextInt(upperBound: 6))
            events.append(MIDIEvent(stepIndex: bar * 16 + offset, note: UInt8(note),
                                    velocity: UInt8(vel), durationSteps: hold))
            let endBar = (bar * 16 + offset + hold + 15) / 16
            onsets.append((startBar: bar, endBar: endBar))
            bar = endBar + 4 + rng.nextInt(upperBound: 4)            // 4–7 bars of rest
        }
    }

    // MARK: - Remix Break pickup

    /// Three eighths on steps 10, 12 and 14 of the remix's last bar, climbing by scale step to
    /// a chord tone on the downbeat of the return. Played on both exits — the unison stabs and
    /// the fill — so the lead is what brings the song back in.
    private static func remixPickups(_ returns: [Int], structure: SongStructure, frame: GlobalMusicalFrame,
                                     pool: [Int], rng: inout SeededRNG) -> [MIDIEvent] {
        var events: [MIDIEvent] = []
        for bar in returns {
            guard let chord = structure.chordPlan.first(where: { $0.contains(bar: bar) }) else { continue }
            let landings = pool.indices.filter { $0 >= 3 && chord.chordTones.contains(pool[$0] % 12) }
            guard !landings.isEmpty else { continue }
            let mid = pool.count / 2
            let target = landings.min { abs($0 - mid) < abs($1 - mid) }!
            let vel = 70 + rng.nextInt(upperBound: 10)
            for (k, step) in [10, 12, 14].enumerated() {
                events.append(MIDIEvent(stepIndex: (bar - 1) * 16 + step, note: UInt8(pool[target - 3 + k]),
                                        velocity: UInt8(vel - 6 + 3 * k), durationSteps: 2))
            }
            events.append(MIDIEvent(stepIndex: bar * 16, note: UInt8(pool[target]),
                                    velocity: UInt8(vel + 4), durationSteps: 6))
        }
        return events
    }

    // MARK: - Shared

    private static func pickCell(from bank: [(cell: [Int], weight: Double)],
                                 rng: inout SeededRNG) -> [Int] {
        bank[rng.weightedPick(bank.map(\.weight))].cell
    }

    private static func pickCell(rng: inout SeededRNG) -> [Int] {
        pickCell(from: cellBank, rng: &rng)
    }

    private static func velocity(at bar: Int, structure: SongStructure) -> Int {
        switch structure.section(atBar: bar)?.label {
        case .B?:     return 72
        case .outro?: return 58
        default:      return 67
        }
    }

    /// The chord tone of `bar` nearest `pitch`, so a phrase starts on the harmony and close to
    /// where the last one left off.
    private static func anchor(near pitch: Int, bar: Int, structure: SongStructure,
                               frame: GlobalMusicalFrame, pool: [Int]) -> Int {
        let tones = structure.chordPlan.first { $0.contains(bar: bar) }?.chordTones ?? []
        let candidates = pool.filter { tones.contains($0 % 12) }
        return (candidates.isEmpty ? pool : candidates).min { abs($0 - pitch) < abs($1 - pitch) }!
    }

    /// Plays a figure from `pitch` on the scale. Repeated pitches stay repeated; any other
    /// interval moves at least one scale step in its own direction, and turns back at the edge
    /// of the register. Notes are legato — each holds until the next — and anything that would
    /// run past `limit` is cut.
    private static func realise(_ phrase: SohoPhrase, at start: Int, from pitch: Int, limit: Int,
                                pool: [Int], vel: Int, rng: inout SeededRNG) -> [MIDIEvent] {
        var events: [MIDIEvent] = []
        var idx = pool.indices.min { abs(pool[$0] - pitch) < abs(pool[$1] - pitch) } ?? 0
        var step = start
        for (i, dur) in phrase.durs.enumerated() {
            guard step < limit else { break }
            if i > 0 {
                let iv = phrase.intervals[i - 1]
                if iv != 0 {
                    var target = pool[idx] + iv
                    if target > pool[pool.count - 1] || target < pool[0] { target = pool[idx] - iv }
                    var next = pool.indices.min { abs(pool[$0] - target) < abs(pool[$1] - target) } ?? idx
                    if next == idx { next = Swift.min(pool.count - 1, Swift.max(0, idx + (target > pool[idx] ? 1 : -1))) }
                    idx = next
                }
            }
            let accent = i == 0 ? 3 : (i == phrase.durs.count - 1 ? -3 : 0)
            let v = Swift.max(40, Swift.min(110, vel + accent + rng.nextInt(upperBound: 9) - 4))
            events.append(MIDIEvent(stepIndex: step, note: UInt8(pool[idx]), velocity: UInt8(v),
                                    durationSteps: Swift.min(dur, limit - step)))
            step += dur
        }
        return events
    }
